function getInitialLanguage() {
  try {
    const saved = localStorage.getItem("ca1n_lang");
    if (saved === "tr" || saved === "en") {
      return saved;
    }
  } catch (_) {
    // Ignore storage access errors in private browsing
  }
  return "tr";
}

function getActiveLanguage() {
  return document.documentElement.lang === "en" ? "en" : "tr";
}

function applyLanguage(lang) {
  const activeLang = lang === "en" ? "en" : "tr";
  const dict = TRANSLATIONS[activeLang];

  document.documentElement.lang = activeLang;

  const titleKey = document.documentElement.getAttribute("data-i18n-title");
  if (titleKey && dict[titleKey]) {
    document.title = dict[titleKey];
  }

  for (const el of document.querySelectorAll("[data-i18n]")) {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.textContent = dict[key];
    }
  }

  for (const el of document.querySelectorAll("[data-i18n-html]")) {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  }

  for (const btn of document.querySelectorAll(".lang-btn[data-lang]")) {
    const isCurrent = btn.getAttribute("data-lang") === activeLang;
    btn.setAttribute("aria-pressed", isCurrent ? "true" : "false");
  }

  try {
    localStorage.setItem("ca1n_lang", activeLang);
  } catch (_) {
    // Ignore storage errors
  }
}

function initSupportForm() {
  const form = document.getElementById("support-request-form");
  if (!form) return;

  const emailInput = document.getElementById("support-email");
  const messageInput = document.getElementById("support-message");
  const nameInput = document.getElementById("support-name");
  const statusEl = document.getElementById("support-form-status");

  const clearStatus = () => {
    if (statusEl) {
      statusEl.textContent = "";
      statusEl.classList.remove("error");
    }
  };

  for (const field of [emailInput, messageInput]) {
    if (!field) continue;
    field.addEventListener("input", () => {
      field.setAttribute("aria-invalid", "false");
      clearStatus();
    });
  }

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const lang = getActiveLanguage();
    const dict = TRANSLATIONS[lang];

    if (!form.checkValidity()) {
      const firstInvalid = form.querySelector(":invalid");
      if (firstInvalid) {
        firstInvalid.setAttribute("aria-invalid", "true");
        firstInvalid.focus();
      }
      if (statusEl) {
        statusEl.textContent = dict["support.form.status_err"];
        statusEl.classList.add("error");
      }
      return;
    }

    const topicRadio = form.querySelector('input[name="topic"]:checked');
    const topicLabel = topicRadio ? topicRadio.parentElement.textContent.trim() : "E Scooter GO! Support";
    const senderName = nameInput ? nameInput.value.trim() : "";
    const senderEmail = emailInput ? emailInput.value.trim() : "";
    const messageBody = messageInput ? messageInput.value.trim() : "";

    const subject = `[E Scooter GO!] ${topicLabel}`;
    const bodyLines = [
      senderName ? `Name: ${senderName}` : null,
      `Reply-To: ${senderEmail}`,
      `Topic: ${topicLabel}`,
      "",
      messageBody
    ].filter((line) => line !== null).join("\n");

    if (statusEl) {
      statusEl.classList.remove("error");
      statusEl.textContent = dict["support.form.status_ok"];
    }

    window.location.href = `mailto:zaptciogluc@gmail.com?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(bodyLines)}`;
  });
}

document.addEventListener("DOMContentLoaded", () => {
  const initialLang = getInitialLanguage();
  applyLanguage(initialLang);

  for (const btn of document.querySelectorAll(".lang-btn[data-lang]")) {
    btn.addEventListener("click", () => {
      const targetLang = btn.getAttribute("data-lang");
      applyLanguage(targetLang);
    });
  }

  initSupportForm();
});
