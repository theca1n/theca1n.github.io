function getInitialLanguage() {
  try {
    const saved = localStorage.getItem("ca1n_lang");
    if (saved === "tr" || saved === "en") {
      return saved;
    }
  } catch (_) {
    // Ignore storage access errors in private browsing
  }
  const browserLang = (navigator.language || "tr").toLowerCase();
  return browserLang.startsWith("en") ? "en" : "tr";
}

function applyLanguage(lang) {
  const activeLang = lang === "en" ? "en" : "tr";
  const dict = TRANSLATIONS[activeLang];

  document.documentElement.lang = activeLang;

  const titleKey = document.documentElement.getAttribute("data-i18n-title");
  if (titleKey && dict[titleKey]) {
    document.title = dict[titleKey];
  }

  for (const el of document.querySelectorAll("[data-i18n]")) {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.textContent = dict[key];
    }
  }

  for (const el of document.querySelectorAll("[data-i18n-html]")) {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  }

  for (const btn of document.querySelectorAll(".lang-btn[data-lang]")) {
    const isCurrent = btn.getAttribute("data-lang") === activeLang;
    btn.setAttribute("aria-pressed", isCurrent ? "true" : "false");
  }

  try {
    localStorage.setItem("ca1n_lang", activeLang);
  } catch (_) {
    // Ignore storage errors
  }
}

document.addEventListener("DOMContentLoaded", () => {
  const initialLang = getInitialLanguage();
  applyLanguage(initialLang);

  for (const btn of document.querySelectorAll(".lang-btn[data-lang]")) {
    btn.addEventListener("click", () => {
      const targetLang = btn.getAttribute("data-lang");
      applyLanguage(targetLang);
    });
  }
});
